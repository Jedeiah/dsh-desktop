  var current = 'zh';

  function t(key, vars) {
    var table = DICT[current] || DICT.zh;
    var s = table[key];
    if (s === void 0) s = DICT.zh[key];
    if (s === void 0) return key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, function (_, k) {
        return vars[k] === void 0 ? '' : String(vars[k]);
      });
    }
    return s;
  }

  function applyStatic(root) {
    root = root || document;
    var nodes = root.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    ['title', 'placeholder', 'aria-label'].forEach(function (attr) {
      var sel = '[data-i18n-' + attr + ']';
      var list = root.querySelectorAll(sel);
      for (var j = 0; j < list.length; j++) {
        list[j].setAttribute(attr, t(list[j].getAttribute('data-i18n-' + attr)));
      }
    });
  }

  function setLocale(locale) {
    var want = String(locale || '').toLowerCase().indexOf('en') === 0 ? 'en' : 'zh';
    current = want;
    document.documentElement.lang = want === 'en' ? 'en' : 'zh-CN';
    if (document.body) applyStatic(document);
    return current;
  }

  window.DSH_I18N = { t: t, setLocale: setLocale, applyStatic: applyStatic,
                       get locale() { return current; } };
